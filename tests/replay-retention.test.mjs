import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, stat } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { archiveReplays, listReplays, isReplayExcluded } from '../src/history.mjs';
import { saveReplaySettings, validateReplaySettings } from '../src/replay-settings.mjs';
import { cleanReplayRetention, retentionPreview } from '../src/replay-retention.mjs';
import { configureCoachSync, enqueueCoachBundle, syncCoachBundles } from '../src/coach-sync.mjs';
import { bundle, harness } from './helpers/cloud-review-fixture.mjs';
const recent = () => new Date(Date.now() - 86400000).toISOString();
test('retention deletes local archive and outbox, reclaims disk, and prevents reimport without cloud tombstones', async t => {
  const dataDir = await mkdtemp(join(tmpdir(), 'replay-retention-'));
  t.after(() => rm(dataDir, { recursive: true, force: true }));
  const old = { match: { id: 'old-local', started_at: '2020-01-01T00:00:00Z' }, games: [], warnings: ['x'.repeat(2 * 1024 * 1024)] };
  const fresh = { match: { id: 'recent-local', started_at: recent() }, games: [] };
  await archiveReplays([old, fresh], { dataDir });
  await archiveReplays([old], { dataDir: join(dataDir, 'replay-outbox') });
  await saveReplaySettings({ retention_days: 7 }, dataDir);
  const before = (await stat(join(dataDir, 'replays.sqlite3'))).size;
  assert.equal((await retentionPreview({ dataDir })).expired_records, 2);
  const cleaned = await cleanReplayRetention({ dataDir });
  assert.equal(cleaned.deleted_records, 2);
  assert.ok((await stat(join(dataDir, 'replays.sqlite3'))).size < before);
  assert.deepEqual((await listReplays({ dataDir })).map(row => row.id), ['recent-local']);
  assert.equal(await isReplayExcluded('old-local', { dataDir }), false);
  assert.equal((await archiveReplays([old], { dataDir })).archived, 0);
  assert.equal((await listReplays({ dataDir: join(dataDir, 'replay-outbox') })).length, 0);
  assert.equal((await cleanReplayRetention({ dataDir })).deleted_records, 0);
  for (const value of [-1, 0, 1.5, '30', 36501]) assert.throws(() => validateReplaySettings({ retention_days: value }));
});
test('sparse local cleanup keeps published old data online and later new uploads work', async t => {
  const h = await harness(t);
  await configureCoachSync('fixture-owner/private-coaching', h.options);
  const old = await bundle({ id: 'expired-online', started: '2020-01-01T00:00:00Z' });
  const current = await bundle({ id: 'recent-online', started: recent() });
  await enqueueCoachBundle(old, h.options); await enqueueCoachBundle(current, h.options);
  await syncCoachBundles({ ...h.options, fastSync: true });
  await saveReplaySettings({ retention_days: 7 }, h.dataDir);
  await cleanReplayRetention({ dataDir: h.dataDir });
  await assert.rejects(stat(join(h.checkout, 'matches', old.historyKey, 'coach.json')), { code: 'ENOENT' });
  assert.ok(await h.published(`matches/${old.historyKey}/coach.json`));
  const next = await bundle({ id: 'new-after-cleanup', started: recent() });
  await enqueueCoachBundle(next, h.options); await syncCoachBundles({ ...h.options, fastSync: true });
  assert.ok((JSON.parse(await h.published('index.json'))).matches.some(row => row.match_id === next.summary.match_id));
});
test('expired data from a failed outgoing push cannot hitchhike on a later recent upload', async t => {
  const h = await harness(t);
  await configureCoachSync('fixture-owner/private-coaching', h.options);
  await enqueueCoachBundle(await bundle({ id: 'baseline', started: recent() }), h.options);
  await syncCoachBundles({ ...h.options, fastSync: true });
  await enqueueCoachBundle(await bundle({ id: 'must-stay-local', started: '2020-01-01T00:00:00Z' }), h.options);
  h.control.rejectPush = true;
  await assert.rejects(syncCoachBundles({ ...h.options, fastSync: true }));
  h.control.rejectPush = false;
  await saveReplaySettings({ retention_days: 7 }, h.dataDir);
  await cleanReplayRetention({ dataDir: h.dataDir });
  await enqueueCoachBundle(await bundle({ id: 'recent-retry', started: recent() }), h.options);
  await syncCoachBundles({ ...h.options, fastSync: true });
  const ids = JSON.parse(await h.published('index.json')).matches.map(row => row.match_id);
  assert.ok(ids.includes('recent-retry'));
  assert.ok(!ids.includes('must-stay-local'));
});
