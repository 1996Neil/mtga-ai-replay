export async function enqueueCoachBundle(bundle, options = {}) {
  if (isTutorialMatch(bundle?.summary) || await isReplayExcluded(bundle?.summary?.match_id, options)) fail('SYNC_EXCLUDED', 'This replay is excluded from upload.');
  const dataDir = options.dataDir ?? defaultDataDir(), files = options.computePool ? await options.computePool.run('bundleFiles',{bundle}) : bundleFiles(bundle);
  return locked(dataDir, async () => {
    const state = await readState(dataDir), id = bundle.summary.match_id;
    if (await isReplayExcluded(id, { dataDir })) fail('SYNC_EXCLUDED', 'This replay is excluded from upload.');
    const stableKey = state.synced[id]?.history_key ?? state.pending.find(item => item.match_id === id)?.history_key;
    if (stableKey && stableKey !== bundle.historyKey) fail('SYNC_BUNDLE', 'The match history key changed; regenerate with its existing stable history key.');
    if (state.synced[id]?.content_hash === bundle.contentHash && !state.pending.some(item => item.match_id === id)) return { queued: false, duplicate: true };
    const existing = state.pending.find(item => item.match_id === id);
    if (existing?.content_hash === bundle.contentHash && existing.history_key === bundle.historyKey) return { queued: false, duplicate: true };
    const queueRelative = `bundles/${bundle.historyKey}/${bundle.contentHash}`;
    await safeOutputParents(locations(dataDir).root, `${queueRelative}/summary.json`);
    const queuePath = join(locations(dataDir).root, queueRelative);
    for (const [name, content] of files) {
      await safeOutputParents(queuePath, name); await atomicWrite(join(queuePath, name), content);
    }
    const item = { match_id: id, started_at: bundle.summary.started_at, history_key: bundle.historyKey, content_hash: bundle.contentHash };
    state.pending = [...state.pending.filter(value => value.match_id !== id), item];
    await saveState(dataDir, state); return { queued: true, pending: state.pending.length };
  });
}

async function safeDirectory(path) {
  try { const value = await lstat(path); if (!value.isDirectory() || value.isSymbolicLink()) fail('SYNC_WORKTREE', 'Sync checkout must be a real directory.'); }
  catch (error) { if (error.code === 'ENOENT') { await mkdir(path, { mode: 0o700 }); return; } throw error; }
}
async function safeOutputParents(repoDir, relative) {
  let parent = repoDir;
  for (const component of relative.split('/').slice(0, -1)) {
    parent = join(parent, component); await safeDirectory(parent);
  }
}
async function verifyRemote(git, repository) {
  const expected = `https://github.com/${repository}.git`;
  for (const flags of [[], ['--push']]) {
    const urls = String(await git(['remote', 'get-url', '--all', ...flags, 'origin'])).trim().split('\n');
    if (urls.length !== 1 || urls[0] !== expected) fail('SYNC_REMOTE', 'Sync remote differs from the verified private repository.');
  }
}
async function prepareCheckout(state, meta, run, repoDir, options = {}) {
  await safeDirectory(repoDir);
  const { name: author, email } = SYNC_IDENTITY;
  const git = (args, encoding = 'utf8', input) => run('git', ['-c', 'credential.helper=', '-c', 'credential.helper=!gh auth git-credential',
    '-c', 'core.hooksPath=/dev/null', '-c', 'commit.gpgsign=false', '-c', `user.name=${author}`,
    '-c', `user.email=${email}`,
    // A real large HTTPS push returned HTTP 400 on this Mac. Use a bounded
    // transport buffer, retain TLS checks, and leave global Git config untouched.
    // Publish only the requested data branch. A user's followTags preference
    // must not attach local annotated tags whose metadata is not in this guard.
    ...(args[0] === 'push' ? ['-c', 'http.version=HTTP/1.1', '-c', 'http.postBuffer=67108864', '-c', 'push.followTags=false'] : []),
    ...args], { cwd: repoDir, encoding, input,
    env: { GIT_AUTHOR_NAME: author, GIT_AUTHOR_EMAIL: email, GIT_COMMITTER_NAME: author, GIT_COMMITTER_EMAIL: email,
      GIT_DIR: join(repoDir, '.git'), GIT_WORK_TREE: repoDir, GIT_INDEX_FILE: join(repoDir, '.git', 'index') },
    timeout: args[0] === 'push' ? PUSH_TIMEOUT_MS : undefined, operation: args[0] });
  const remote = `https://github.com/${meta.nameWithOwner}.git`, branch = meta.defaultBranchRef?.name || 'main';
  const historyOptions = { repository: meta.nameWithOwner, branch,
    historyApproval: validateSyncHistoryApproval(state.history_approval, { repository: meta.nameWithOwner, branch }) };
  const validationSession = options.validationSession ?? createSyncValidationSession();
  const validate = async historyRevision => {
    if (options.fastSync) {
      options.onProgress?.({ phase: 'comparing' });
      return validateSyncChanges(git, { branch, onValidation: options.onValidation });
    }
    options.onProgress?.({ phase: 'security' });
    return validateStagedRepository(repoDir, { ...historyOptions, validationSession,
      ...(historyRevision ? { historyRevision } : {}), computePool:options.computePool,
      onValidation: value => options.onValidation?.({ ...value, history_revision: historyRevision ?? null }), gitBatchFactory: options.gitBatchFactory ? ()=>options.gitBatchFactory({repoDir}) : !options.runCommand ? ()=>createGitBatch({cwd:repoDir,gitArgs:['-c','core.hooksPath=/dev/null','-c','commit.gpgsign=false'],env:{GIT_DIR:join(repoDir,'.git'),GIT_WORK_TREE:repoDir,GIT_INDEX_FILE:join(repoDir,'.git/index'),GIT_TERMINAL_PROMPT:'0',GIT_CONFIG_NOSYSTEM:'1'}}) : undefined, runGit: (args, settings) => git(args, settings.encoding, settings.input) });
  };
  let exists = false;
  try { const stat = await lstat(join(repoDir, '.git')); exists = stat.isDirectory() && !stat.isSymbolicLink(); if (!exists) fail('SYNC_WORKTREE', 'Unexpected sync checkout metadata.'); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (!exists) { await git(['init', '-b', branch]); await git(['remote', 'add', 'origin', remote]); }
  await verifyRemote(git, meta.nameWithOwner);
  if (String(await git(['branch', '--show-current'])).trim() !== branch) fail('SYNC_BRANCH', 'Sync checkout is on an unexpected branch.');
  // Check before fetching or merging: even a fast-forward must not overwrite
  // another writer's staged, ignored or otherwise uncommitted files.
  if (!options.deferFullHistoryValidation && !options.fastSync) await validate();
  if (String(await git(['status', '--porcelain', '--untracked-files=all', '--ignored=matching'])).trim()) fail('SYNC_DIRTY', 'Sync checkout contains uncommitted files; no files were overwritten.');
  options.onProgress?.({ phase: 'remote' });
  await git(['fetch', '--prune', 'origin']);
  if (!options.deferFullHistoryValidation && !options.fastSync) await validate();
  if (meta.defaultBranchRef?.name) {
    const localRefs = String(await git(['show-ref']));
    if (localRefs.includes(`refs/heads/${branch}`)) await git(['merge', '--ff-only', `origin/${branch}`]);
    else await git(['checkout', '-B', branch, `origin/${branch}`]);
  }
  if (!options.deferFullHistoryValidation) await validate();
  const changes = String(await git(['status', '--porcelain', '--untracked-files=all', '--ignored=matching'])).trim();
  if (changes) fail('SYNC_DIRTY', 'Sync checkout contains uncommitted files; no files were overwritten.');
  return { git, branch, validate };
}

/** A failed push leaves safe commits locally. Only their owning command may
 * retry them: otherwise one namespace could silently publish the other. */
export async function assertOutgoingSyncOwnership(git, branch, namespace, hasRemoteBranch) {
  const hasHead = String(await git(['for-each-ref', '--format=%(refname)', `refs/heads/${branch}`])).trim();
  if (!hasHead) return;
  const revisions = String(await git(['rev-list', hasRemoteBranch ? `origin/${branch}..HEAD` : 'HEAD'])).trim().split('\n').filter(Boolean);
  const allowed = namespace === 'draft' ? isDraftSyncPath : namespace === 'collection' ? isCollectionSyncPath : namespace === 'coach' ? isCoachSyncPath : null;
  if (!allowed) fail('SYNC_NAMESPACE', 'Unknown upload namespace.');
  for (const revision of revisions) {
    const paths = String(await git(['diff-tree', '--root', '-m', '--no-commit-id', '--name-only', '--no-renames', '-r', '-z', revision])).split('\0').filter(Boolean);
    if (paths.some(path => !allowed(path))) fail('SYNC_FOREIGN_COMMIT', 'Sync checkout contains an unpublished commit belonging to another namespace; finish that sync first.');
  }
}
export async function assertStagedSyncOwnership(git, namespace) {
  const allowed = namespace === 'draft' ? isDraftSyncPath : namespace === 'collection' ? isCollectionSyncPath : namespace === 'coach' ? isCoachSyncPath : null;
  if (!allowed) fail('SYNC_NAMESPACE', 'Unknown upload namespace.');
  const paths = String(await git(['diff', '--cached', '--name-only', '-z', '--no-ext-diff', '--no-renames'])).split('\0').filter(Boolean);
  if (paths.some(path => !allowed(path))) fail('SYNC_FOREIGN_STAGE', 'Another namespace has staged changes; no commit was created.');
}

