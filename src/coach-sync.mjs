async function atomicWrite(path, content) {
  const temporary = `${path}.${randomUUID()}.tmp`;
  await mkdir(resolve(path, '..'), { recursive: true, mode: 0o700 });
  await writeFile(temporary, content, { mode: 0o600 });
  await rename(temporary, path);
}
async function readState(dataDir) {
  try {
    const value = JSON.parse(await readFile(locations(dataDir).state, 'utf8'));
    if (value.schema !== 'MTGA_LOCAL_SYNC_V1' || !Array.isArray(value.pending) || !value.synced) fail('SYNC_STATE', 'Local sync state is invalid; no upload was attempted.');
    return value;
  } catch (error) { if (error.code === 'ENOENT') return initialState(); throw error; }
}
const saveState = (dataDir, state) => atomicWrite(locations(dataDir).state, serializeCoachJson(state));

async function locked(dataDir, callback) {
  const { root } = locations(dataDir); await mkdir(root, { recursive: true, mode: 0o700 });
  await safeDirectory(root);
  const path = join(root, 'sync.lock'), recovery = join(root, 'recovery.lock');
  await rejectRecoveryInProgress(recovery);
  let handle;
  try { handle = await open(path, 'wx', 0o600); }
  catch (error) {
    if (error.code !== 'EEXIST') throw error;
    const pid = await readSyncLockPid(path);
    if (pid && isDeadPid(pid)) fail('SYNC_LOCK_STALE', 'A stale MTGA sync lock was retained. Recover explicitly with mtga-gpt-collection status --recover-sync-lock.');
    fail('SYNC_BUSY', 'Another MTGA data sync is running or its lock is incomplete; retry when it finishes.');
  }
  try {
    // A recovery may have started after the first check. Own this new inode,
    // then stop before any callback if the recovery gate is now present.
    await rejectRecoveryInProgress(recovery);
    await handle.writeFile(String(process.pid));
    return await callback();
  } finally { await removeOwnedLock(path, handle); }
}

async function rejectRecoveryInProgress(path) {
  try { await lstat(path); fail('SYNC_BUSY', 'Explicit MTGA sync lock recovery is running; retry when it finishes.'); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
}
async function readSyncLockPid(path) {
  const stat = await lstat(path);
  if (!stat.isFile() || stat.isSymbolicLink()) fail('SYNC_WORKTREE', 'MTGA sync lock must be a regular file.');
  const text = await readFile(path, 'utf8');
  if (!/^[1-9][0-9]{0,9}$/.test(text)) return null;
  const pid = Number(text); return Number.isSafeInteger(pid) && pid <= 2147483647 ? pid : null;
}
function isDeadPid(pid) {
  try { process.kill(pid, 0); return false; }
  catch (error) { return error.code === 'ESRCH'; }
}
async function removeOwnedLock(path, handle) {
  try {
    const own = await handle.stat({ bigint: true });
    try {
      const current = await lstat(path, { bigint: true });
      if (current.dev === own.dev && current.ino === own.ino && current.isFile() && !current.isSymbolicLink()) await rm(path);
    } catch (error) { if (error.code !== 'ENOENT') throw error; }
  } finally { await handle.close(); }
}

/** Explicit recovery only. A separate exclusive gate serializes recovery
 * requests; normal contenders never unlink another process's stale inode. */
export async function recoverCoachSyncLock(options = {}) {
  const { root } = locations(options.dataDir ?? defaultDataDir());
  await mkdir(root, { recursive: true, mode: 0o700 }); await safeDirectory(root);
  const path = join(root, 'sync.lock'), recovery = join(root, 'recovery.lock');
  let gate;
  try { gate = await open(recovery, 'wx', 0o600); }
  catch (error) { if (error.code === 'EEXIST') fail('SYNC_BUSY', 'Another explicit sync lock recovery is present; no lock was removed.'); throw error; }
  try {
    await gate.writeFile(String(process.pid));
    let original;
    try { original = await lstat(path, { bigint: true }); } catch (error) { if (error.code === 'ENOENT') return { recovered: false }; throw error; }
    const pid = await readSyncLockPid(path);
    if (!pid || !isDeadPid(pid)) fail('SYNC_BUSY', 'The MTGA sync lock is live or cannot be verified as stale; no lock was removed.');
    const current = await lstat(path, { bigint: true });
    if (current.dev !== original.dev || current.ino !== original.ino || !current.isFile() || current.isSymbolicLink() ||
        await readSyncLockPid(path) !== pid || !isDeadPid(pid)) fail('SYNC_BUSY', 'The MTGA sync lock changed during recovery; no lock was removed.');
    await rm(path); return { recovered: true };
  } finally { await removeOwnedLock(recovery, gate); }
}

const PUSH_TIMEOUT_MS = 120_000;
function execute(file, args, { cwd, encoding = 'utf8', env = {}, input, timeout = 30_000 } = {}) {
  return new Promise((yes, no) => {
  const child = execFile(file, args, {
    cwd, encoding, timeout, maxBuffer: 512 * 1024 * 1024,
    env: { ...process.env, ...env, GIT_TERMINAL_PROMPT: '0', GIT_CONFIG_NOSYSTEM: '1' },
  }, (error, stdout) => error ? no(error) : yes(stdout));
  child.stdin.on('error', no); child.stdin.end(input);
  });
}
function runner(options) {
  const run = options.runCommand ?? execute;
  return async (file, args, settings) => {
    try {
      const result = await run(file, args, settings);
      return result && typeof result === 'object' && !(result instanceof Uint8Array) ? result.stdout : result;
    } catch (error) {
      // Never interpolate stderr, token-bearing URLs or command arguments.
      if (file === 'git' && settings?.operation === 'push') {
        // Node versions report execFile's timeout either as ETIMEDOUT or as
        // a killed child with SIGTERM. The push has an explicit timeout, so
        // treat both shapes as an ambiguous remote outcome.
        const timedOut = error?.code === 'ETIMEDOUT' || (settings?.timeout > 0 && error?.killed === true && error?.signal === 'SIGTERM');
        fail(timedOut ? 'SYNC_PUSH_TIMEOUT' : 'SYNC_PUSH_FAILED', timedOut
          ? 'Git push timed out; remote outcome is unverified and pending work was retained. Verify the remote branch before retrying.'
          : 'Git push failed; remote outcome is unverified and pending work was retained.');
      }
      fail(file === 'gh' ? 'GITHUB_UNAVAILABLE' : 'GIT_FAILED', file === 'gh'
        ? 'GitHub authentication or network is unavailable; local replay remains usable.'
        : 'Git sync failed or the remote rejected the update; pending work was retained.');
    }
  };
}
async function privateRepository(repository, run) {
  if (!REPOSITORY.test(repository ?? '')) fail('SYNC_REPOSITORY', 'Repository must be in owner/name form.');
  let meta;
  try { meta = JSON.parse(await run('gh', ['repo', 'view', repository, '--json', 'nameWithOwner,visibility,url,defaultBranchRef'])); }
  catch (error) { if (error instanceof CoachSyncError) throw error; fail('GITHUB_UNAVAILABLE', 'GitHub repository verification failed.'); }
  if (meta.visibility !== 'PRIVATE') fail('SYNC_NOT_PRIVATE', 'Upload blocked: the GitHub repository is not PRIVATE.');
  if (String(meta.nameWithOwner).toLowerCase() !== repository.toLowerCase() || meta.url !== `https://github.com/${meta.nameWithOwner}`) fail('SYNC_REPOSITORY', 'GitHub repository identity could not be verified.');
  if (meta.defaultBranchRef?.name && !/^[A-Za-z0-9_.\/-]+$/.test(meta.defaultBranchRef.name)) fail('SYNC_BRANCH', 'GitHub default branch is unsupported.');
  return meta;
}
export async function configureCoachSync(repository, options = {}) {
  const dataDir = options.dataDir ?? defaultDataDir();
  return locked(dataDir, async () => {
    const meta = await privateRepository(repository, runner(options));
    const state = await readState(dataDir);
    if (state.repository && state.repository.toLowerCase() !== repository.toLowerCase()) fail('SYNC_REPOSITORY', 'This local sync store is already configured for another repository.');
    Object.assign(state, { enabled: true, repository: meta.nameWithOwner, visibility: meta.visibility, verified_at: new Date().toISOString() });
    await saveState(dataDir, state); return state;
  });
}
export async function getCoachSyncStatus(options = {}) {
  const state = await readState(options.dataDir ?? defaultDataDir());
  let visibility = state.enabled ? 'UNKNOWN' : null;
  if (state.enabled && options.verify !== false) {
    try { visibility = (await privateRepository(state.repository, runner(options))).visibility; }
    catch (error) { if (error.code === 'SYNC_NOT_PRIVATE') visibility = 'NOT_PRIVATE'; }
  } else if (state.enabled) visibility = state.visibility ?? 'UNKNOWN';
  return { enabled: state.enabled, repository: state.repository, visibility,
    last_synced: state.last_synced, pending: state.pending.length, last_error: state.last_error ?? null };
}
/** Called only after explicit human consent; this record stays in the private sync store. */
export async function approveCoachSyncHistory(approval, options = {}) {
  const dataDir = options.dataDir ?? defaultDataDir();
  return locked(dataDir, async () => {
    const state = await readState(dataDir);
    if (!state.enabled) fail('SYNC_REPOSITORY', 'Private replay sync is not configured.');
    const meta = await privateRepository(state.repository, runner(options));
    state.history_approval = validateSyncHistoryApproval(approval, { repository: meta.nameWithOwner, branch: meta.defaultBranchRef?.name || 'main' });
    if (!state.history_approval) fail('SYNC_STATE', 'Explicit history approval is required.');
    await saveState(dataDir, state);
    return state.history_approval;
  });
}
