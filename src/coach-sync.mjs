async function queuedFiles(item, dataDir, computePool) {
  if (!HISTORY_KEY.test(item.history_key ?? '') || !SHA.test(item.content_hash ?? '')) fail('SYNC_STATE', 'Invalid pending bundle reference.');
  const directory = join(locations(dataDir).root, 'bundles', item.history_key, item.content_hash);
  await safeOutputParents(locations(dataDir).root, `bundles/${item.history_key}/${item.content_hash}/summary.json`);
  const files = new Map();
  for (const name of NAMES) {
    const file = join(directory, name), stat = await lstat(file);
    if (!stat.isFile() || stat.isSymbolicLink()) fail('SYNC_WORKTREE', 'Pending bundle must contain regular files.');
    files.set(name, await readFile(file, 'utf8'));
  }
  const values = Object.fromEntries([...files].map(([name, text]) => [name.slice(0, -5), JSON.parse(text)]));
  if (isTutorialMatch(values.summary) || isTutorialMatch(values.coach?.match) ||
      await isReplayExcluded(item.match_id, { dataDir })) fail('SYNC_EXCLUDED', 'This replay is excluded from upload.');
  // Publish exactly the bytes whose parsed structure was scanned. Canonical equality
  // also rejects duplicate JSON keys that JSON.parse would silently discard.
  for (const name of NAMES) {
    const text = files.get(name);
    if (text !== serializeCoachJson(values[name.slice(0, -5)])) fail('SYNC_BUNDLE', 'Pending main file bytes are not canonical; no upload was attempted.');
    if (name !== 'manifest.json') {
      const expected = values.manifest.files?.[name];
      if (expected?.sha256 !== digest(text) || expected.bytes !== Buffer.byteLength(text)) fail('SYNC_BUNDLE', 'Pending main file integrity check failed; no upload was attempted.');
    }
  }
  const parts = new Map();
  for (const name of Object.keys(values.manifest.files ?? {})) {
    if (NAMES.includes(name)) continue;
    if (PART_PATH.exec(name)?.[1] !== item.history_key) fail('SYNC_BUNDLE', 'Pending object part path is invalid.');
    await safeOutputParents(directory, name);
    const path = join(directory, name), stat = await lstat(path);
    if (!stat.isFile() || stat.isSymbolicLink()) fail('SYNC_WORKTREE', 'Pending object part must be a regular file.');
    const text = await readFile(path, 'utf8'); parts.set(name, text); files.set(name, text);
  }
  const bundle = { ...values, parts, historyKey: item.history_key, contentHash: item.content_hash };
  if (computePool) await computePool.run('bundleFiles',{bundle}); else bundleFiles(bundle);
  if (values.summary.match_id !== item.match_id || values.summary.started_at !== item.started_at) fail('SYNC_STATE', 'Pending bundle metadata differs from its contents.');
  return { files, summary: values.summary };
}
const byDate = (a, b) => String(b.started_at).localeCompare(String(a.started_at)) || a.match_id.localeCompare(b.match_id);
function publishedIndex(text) {
  let index;
  try { index = JSON.parse(text); } catch { fail('SYNC_INDEX', 'Published match index is invalid.'); }
  if (index?.schema !== 'MTGA_COACH_INDEX_V1' || !Array.isArray(index.matches)) fail('SYNC_INDEX', 'Published match index is invalid.');
  const ids = new Set(), keys = new Set();
  for (const item of index.matches) {
    if (typeof item.match_id !== 'string' || !item.match_id || ids.has(item.match_id) || keys.has(item.history_key) ||
        !HISTORY_KEY.test(item.history_key ?? '') || item.path !== `matches/${item.history_key}` ||
        !SHA.test(item.content_hash ?? '') || !Number.isFinite(Date.parse(item.started_at))) fail('SYNC_INDEX', 'Published match identity or history path is invalid.');
    ids.add(item.match_id); keys.add(item.history_key);
  }
  return index;
}

/** Compare against fetched remote commits, never an unpushed local index.
 * Cached receipts are only an offline fallback, not proof of remote publication. */
export async function getPublishedCoachIndex(options = {}) {
  const dataDir = options.dataDir ?? defaultDataDir();
  if (options.refresh === false) {
    const state = await readState(dataDir);
    const matches = Object.entries(state.synced).map(([match_id, value]) => ({ ...value, match_id })).sort(byDate);
    return { source: 'cached', pending: state.pending, index: { schema: 'MTGA_COACH_INDEX_V1', matches, latest_match_id: matches[0]?.match_id ?? null } };
  }
  return locked(dataDir, async () => {
    const state = await readState(dataDir);
    if (!state.enabled) fail('SYNC_REPOSITORY', 'Private replay sync is not configured.');
    const run = runner(options); options.onProgress?.({ phase: 'remote' });
    const meta = await privateRepository(state.repository, run);
    const { git, branch } = await prepareCheckout(state, meta, run, locations(dataDir).repo,
      { ...options, deferFullHistoryValidation: false });
    await assertOutgoingSyncOwnership(git, branch, 'coach', Boolean(meta.defaultBranchRef?.name));
    let index = { schema: 'MTGA_COACH_INDEX_V1', matches: [] }, commit = null;
    if (meta.defaultBranchRef?.name) {
      const ref = `origin/${branch}`;
      commit = String(await git(['rev-parse', ref])).trim();
      if (String(await git(['ls-tree', '--name-only', ref, '--', 'index.json'])).trim()) index = publishedIndex(await git(['show', `${ref}:index.json`]));
    }
    // Reconcile remote deletions and externally published matches. Stable keys
    // now come from the actual remote; unpushed bundles remain in pending.
    state.history_keys = { ...state.history_keys, ...Object.fromEntries(Object.entries(state.synced).map(([id, value]) => [id, value.history_key])) };
    state.synced = Object.fromEntries(index.matches.map(item => [item.match_id, {
      history_key: item.history_key, content_hash: item.content_hash, started_at: item.started_at,
    }]));
    await saveState(dataDir, state);
    return { source: 'remote', index, commit, pending: state.pending, destination_hash:createHash('sha256').update(`${state.repository}:${branch}`).digest('hex') };
  });
}
async function publishPending(state, dataDir, options) {
  const run = runner(options); options.onProgress?.({ phase: 'remote' });
  const meta = await privateRepository(state.repository, run), repoDir = locations(dataDir).repo;
  const { git, branch, validate } = await prepareCheckout(state, meta, run, repoDir, options);
  options.onProgress?.({ phase: 'publishing' });
  await assertOutgoingSyncOwnership(git, branch, 'coach', Boolean(meta.defaultBranchRef?.name));
  let collectionEntry = '';
  try { await readFile(join(repoDir, 'collection', 'README.md'), 'utf8'); collectionEntry = COLLECTION_ENTRY; }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  let index;
  try { index = publishedIndex(await readFile(join(repoDir, 'index.json'), 'utf8')); }
  catch (error) { if (error.code !== 'ENOENT') fail('SYNC_INDEX', 'Published match index is invalid.'); index = { schema: 'MTGA_COACH_INDEX_V1', matches: [] }; }
  if (index.schema !== 'MTGA_COACH_INDEX_V1' || !Array.isArray(index.matches)) fail('SYNC_INDEX', 'Published match index is invalid.');
  let committed = 0;
  for (const item of [...state.pending].sort((a, b) => -byDate(a, b))) {
    const { files, summary } = await queuedFiles(item, dataDir, options.computePool);
    const previous = index.matches.find(match => match.match_id === item.match_id);
    if (previous && previous.history_key !== item.history_key) fail('SYNC_BUNDLE', 'Published history key differs from the queued bundle; regenerate with its existing stable history key.');
    if (previous?.content_hash === item.content_hash) continue;
    const path = `matches/${previous?.history_key ?? item.history_key}`;
    if (!HISTORY_KEY.test(path.slice(8))) fail('SYNC_INDEX', 'Published match history path is invalid.');
    const entry = { match_id: item.match_id, started_at: item.started_at, mode: summary.mode, result: summary.result,
      history_key: path.slice(8), path, content_hash: item.content_hash };
    index.matches = [...index.matches.filter(match => match.match_id !== item.match_id), entry].sort(byDate);
    index.latest_match_id = index.matches[0].match_id;
    index.latest = { summary: 'latest/summary.json', coach: 'latest/coach.json', cards: 'latest/cards.json', manifest: 'latest/manifest.json' };
    const writes = new Map([...files].map(([name, text]) => [NAMES.includes(name) ? `${path}/${name}` : name, text]));
    if (index.latest_match_id === item.match_id) for (const name of NAMES) writes.set(`latest/${name}`, files.get(name));
    writes.set('index.json', serializeCoachJson(index)); writes.set('README.md', README + collectionEntry); writes.set('.gitignore', GITIGNORE);
    if(options.computePool)await options.computePool.run('validateFiles',{files:writes});else validateBundleFiles(writes);
    for (const [path, text] of writes) {
      // Existing symlinks and gitlinks were rejected by the Git-object guard.
      await safeOutputParents(repoDir, path);
      const target = join(repoDir, path);
      try { if ((await lstat(target)).isSymbolicLink()) fail('SYNC_WORKTREE', 'Sync output cannot be a symbolic link.'); }
      catch (error) { if (error.code !== 'ENOENT') throw error; }
      await atomicWrite(target, text);
    }
    await git(['add', '--', ...writes.keys()]);
    await assertStagedSyncOwnership(git, 'coach');
    if (!options.deferFullHistoryValidation) await validate();
    if (String(await git(['diff', '--cached', '--name-only'])).trim()) {
      await git(['commit', '-m', `${previous ? 'Improve replay coverage' : 'Add replay'} ${item.match_id}`]); committed++;
    }
  }
  // Recheck visibility and outgoing history immediately before the network mutation.
  options.onProgress?.({ phase: 'remote' });
  await privateRepository(state.repository, run);
  const revision = String(await git(['rev-parse', 'HEAD'])).trim();
  if (!/^[0-9a-f]{40,64}$/.test(revision)) fail('SYNC_REVISION', 'Local sync revision could not be verified.');
  const branchRevision = String(await git(['rev-parse', `refs/heads/${branch}`])).trim();
  if (branchRevision !== revision) fail('SYNC_HEAD_CHANGED', 'Local sync branch changed before the upload safety check.');
  await validate(revision);
  const checkedHead = String(await git(['rev-parse', 'HEAD'])).trim();
  const checkedBranch = String(await git(['rev-parse', `refs/heads/${branch}`])).trim();
  if (checkedHead !== revision || checkedBranch !== revision) fail('SYNC_HEAD_CHANGED', 'Local sync branch changed during the upload safety check.');
  if (String(await git(['status', '--porcelain', '--untracked-files=all', '--ignored=matching'])).trim()) {
    fail('SYNC_WORKTREE', 'Sync checkout changed during the upload safety check.');
  }
  const finalMeta = await privateRepository(state.repository, run);
  if (finalMeta.nameWithOwner !== meta.nameWithOwner || (finalMeta.defaultBranchRef?.name || 'main') !== branch) {
    fail('SYNC_BRANCH', 'Verified repository or default branch changed during the upload safety check.');
  }
  await verifyRemote(git, finalMeta.nameWithOwner);
  await assertOutgoingSyncOwnership(git, branch, 'coach', Boolean(finalMeta.defaultBranchRef?.name));
  const remoteCount = meta.defaultBranchRef?.name ? Number(String(await git(['rev-list', '--count', `origin/${branch}..${revision}`])).trim()) : 1;
  options.onProgress?.({ phase: 'uploading', checkpoint: { commit: revision,
    destination_hash: createHash('sha256').update(`${state.repository}:${branch}`).digest('hex') } });
  let pushError;
  if (remoteCount) {
    try { await git(['push', '--set-upstream', 'origin', `${revision}:refs/heads/${branch}`]); }
    catch (error) { pushError = error; }
  }
  // The exact revision was scanned before push. A fresh fetch and exact remote
  // ref check confirms those same content-addressed objects without rescanning.
  try {
    const confirmationMeta = await privateRepository(state.repository, run);
    if (confirmationMeta.nameWithOwner !== meta.nameWithOwner || (confirmationMeta.defaultBranchRef?.name || 'main') !== branch) {
      fail('SYNC_REMOTE_VERIFY', 'Verified remote target changed before publication could be confirmed.');
    }
    await verifyRemote(git, confirmationMeta.nameWithOwner);
    const remoteRef = `refs/heads/${branch}`;
    const remoteOutput = String(await git(['ls-remote', '--heads', 'origin', remoteRef])).trim();
    const remoteLine = remoteOutput.split('\n').find(line => line.split(/\s+/)[1] === remoteRef);
    if (!remoteLine || remoteLine.split(/\s+/)[0] !== revision) {
      fail('SYNC_REMOTE_VERIFY', 'Remote publication could not be confirmed.');
    }
  } catch (error) { throw pushError ?? error; }

  for (const item of state.pending) state.synced[item.match_id] = { content_hash: item.content_hash, history_key: item.history_key, started_at: item.started_at };
  state.pending = []; state.last_error = null; state.visibility = 'PRIVATE'; state.verified_at = new Date().toISOString();
  state.last_synced = { match_id: index.latest_match_id, at: new Date().toISOString(), commit: revision };
  await saveState(dataDir, state);
  return { synced: true, committed, pending: 0, repository: state.repository, last_synced: state.last_synced, index };
}
export async function syncCoachBundles(options = {}) {
  const dataDir = options.dataDir ?? defaultDataDir();
  return locked(dataDir, async () => {
    const state = await readState(dataDir);
    if (!state.enabled) return { synced: false, disabled: true, pending: state.pending.length };
    if (!state.pending.length) return { synced: true, duplicate: true, committed: 0, pending: 0, repository: state.repository, last_synced: state.last_synced };
    try { return await publishPending(state, dataDir, options); }
    catch (error) {
      state.last_error = { code: error.code ?? 'SYNC_FAILED', message: syncErrorMessage(error), at: new Date().toISOString(),
        ...(error.code === 'SYNC_PUSH_TIMEOUT' || error.code === 'SYNC_PUSH_FAILED' ? { remote_outcome: 'unverified' } : {}) };
      await saveState(dataDir, state); throw error;
    }
  });
}
